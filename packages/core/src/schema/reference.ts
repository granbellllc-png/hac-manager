import { configFileGlobs, configKinds, type ConfigKind } from './registry.js';
import { allEditorJsonSchemas, type JsonSchema } from './json-schema.js';

export interface Row {
  readonly path: string;
  readonly type: string;
  readonly required: boolean;
  readonly condition: string;
  readonly description: string;
}

type Node = Record<string, unknown>;

/** Drops 
ull alternatives (layer files allow null to clear a key) and unwraps single-branch unions. */
function normalize(node: Node): Node {
  const alternatives = node['anyOf'] as Node[] | undefined;
  if (!alternatives) return node;
  const rest = alternatives.filter(
    (alternative) => alternative['type'] !== 'null',
  );
  if (rest.length === alternatives.length) return node;
  const { anyOf: _anyOf, ...others } = node;
  void _anyOf;
  return rest.length === 1
    ? { ...others, ...rest[0] }
    : { ...others, anyOf: rest };
}

function describeType(node: Node): string {
  if (typeof node['const'] === 'string') return `\`"${node['const']}"\``;
  if (Array.isArray(node['enum'])) {
    return (node['enum'] as unknown[])
      .map((value) => `\`${String(value)}\``)
      .join(' \\| ');
  }
  const type = node['type'];
  if (type === 'array') {
    const items = node['items'] as Node | undefined;
    return `array of ${items ? describeType(items) : 'any'}`;
  }
  if (typeof type === 'string') return type;
  if (Array.isArray(node['anyOf'])) {
    return [...new Set((node['anyOf'] as Node[]).map(describeType))].join(
      ' \\| ',
    );
  }
  return 'any';
}

function discriminator(node: Node): string {
  const props = node['properties'] as Record<string, Node> | undefined;
  for (const [key, value] of Object.entries(props ?? {})) {
    if (typeof value['const'] === 'string') return `${key} = ${value['const']}`;
  }
  return '';
}

function join(condition: string, label: string): string {
  if (!label) return condition;
  return condition ? `${condition}, ${label}` : label;
}

function collect(
  rawNode: Node,
  path: string,
  required: boolean,
  condition: string,
  rows: Row[],
  emitSelf = true,
): void {
  const node = normalize(rawNode);
  const variants = (node['oneOf'] ?? node['anyOf']) as Node[] | undefined;
  const objects =
    variants?.filter((variant) => variant['type'] === 'object') ?? [];
  const unionOfObjects =
    objects.length > 0 && objects.length === variants?.length;
  if (path && emitSelf) {
    rows.push({
      path,
      type: unionOfObjects ? 'object' : describeType(node),
      required,
      condition,
      description:
        typeof node['description'] === 'string' ? node['description'] : '',
    });
  }
  if (unionOfObjects) {
    for (const variant of objects) {
      collect(
        variant,
        path,
        required,
        join(condition, discriminator(variant)),
        rows,
        false,
      );
    }
  } else if (node['type'] === 'object' && node['properties']) {
    const requiredKeys = new Set(
      (node['required'] as string[] | undefined) ?? [],
    );
    for (const [key, child] of Object.entries(
      node['properties'] as Record<string, Node>,
    )) {
      collect(
        child,
        path ? `${path}.${key}` : key,
        requiredKeys.has(key),
        condition,
        rows,
      );
    }
  } else if (node['type'] === 'array' && node['items']) {
    collect(node['items'] as Node, `${path}[]`, true, condition, rows);
  } else {
    for (const alternative of variants ?? []) {
      if (alternative['type'] === 'object' || alternative['type'] === 'array') {
        collect(alternative, path, required, condition, rows, false);
      }
    }
  }
}

/** Flattens a JSON Schema into documentation rows (dotted key paths). */
export function schemaToRows(schema: JsonSchema): Row[] {
  const rows: Row[] = [];
  const topVariants = schema['oneOf'] as Node[] | undefined;
  for (const variant of topVariants ?? [schema]) {
    collect(variant, '', true, topVariants ? discriminator(variant) : '', rows);
  }
  return rows;
}

function renderKind(kind: ConfigKind, schema: JsonSchema): string {
  return [
    `## \`${kind}\``,
    '',
    `Files: \`${configFileGlobs[kind]}\``,
    '',
    '| Key | Type | Required | When | Description |',
    '| --- | ---- | -------- | ---- | ----------- |',
    ...schemaToRows(schema).map(
      (row) =>
        `| \`${row.path}\` | ${row.type} | ${row.required ? 'yes' : 'no'} | ${row.condition} | ${row.description} |`,
    ),
  ].join('\n');
}
/** Reference documentation generated from the zod schemas (docs/reference/config.md). */
export function renderConfigReference(): string {
  const schemas = allEditorJsonSchemas();
  return [
    '# Configuration reference',
    '',
    '<!-- Generated by `pnpm docs:schema` from the zod schemas. Do not edit by hand. -->',
    '',
    'Every file carries `schema_version: 1`. Unknown keys are rejected; Proxmox keys that HAC Manager does not model go under `extra`. Scalars accept a literal or a tag (`!env`, `!secret`, `!cmd`, `!expr`). In files merged onto defaults, an explicit `null` removes an inherited key.',
    '',
    ...configKinds.flatMap((kind) => [renderKind(kind, schemas[kind]), '']),
  ].join('\n');
}
