/**
 * Host backup file rendering (D-57).
 *
 * The declarative host config is rendered into `/etc/vzdump.conf`, a restic
 * script and a cron fragment. Values are deterministic and sorted. Resolved
 * `Secret` values are refused: credentials belong in root-only files referenced
 * by absolute paths, never embedded in a managed file (AGENTS.md rule 1).
 */

import { posix } from 'node:path';
import type {
  HostBackupConfig,
  ResticBackupConfig,
  VzdumpBackupConfig,
} from '../schema/host-backup.js';
import { Secret } from '../tags/secret.js';

export type HostBackupFileKind = 'vzdump' | 'restic-script' | 'restic-cron';

export interface RenderedHostBackupFile {
  readonly kind: HostBackupFileKind;
  readonly path: string;
  readonly mode: string;
  readonly content: string;
}

export type HostBackupValue = string | number | boolean;

export class HostBackupError extends Error {
  public constructor(message: string) {
    super(message);
    this.name = 'HostBackupError';
  }
}

function renderScalar(value: unknown, field: string): string {
  if (value instanceof Secret) {
    throw new HostBackupError(
      `${field} resolved to a secret. A managed host file must not contain a resolved secret; reference a root-only file by path instead (AGENTS.md rule 1).`,
    );
  }
  if (typeof value === 'string') {
    if (/[\r\n]/.test(value)) {
      throw new HostBackupError(
        `${field} must not contain a newline in a managed host file.`,
      );
    }
    return value;
  }
  if (typeof value === 'number' || typeof value === 'boolean') {
    return String(value);
  }
  throw new HostBackupError(`${field} must be a string, number or boolean.`);
}

function shellQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

/** Deterministic `/etc/vzdump.conf` content. */
export function renderVzdumpConfig(config: VzdumpBackupConfig): string {
  const keys = Object.keys(config.options).sort();
  const lines = keys.map((key) => {
    if (/[\r\n:]/.test(key)) {
      throw new HostBackupError(`vzdump option '${key}' is not a valid key.`);
    }
    return `${key}: ${renderScalar(config.options[key], `vzdump.options.${key}`)}`;
  });
  return lines.length > 0 ? `${lines.join('\n')}\n` : '';
}

function resticCommandBase(): string[] {
  return ['restic'];
}

/** Generated restic backup script. No secrets are embedded. */
export function renderResticScript(config: ResticBackupConfig): string {
  if (!config.repository && !config.repository_file) {
    throw new HostBackupError('restic requires repository or repository_file.');
  }
  const lines = [
    '#!/bin/sh',
    '# Generated by HAC Manager (D-57). Do not edit; changes are overwritten.',
    'set -eu',
    `status_file=${shellQuote(config.status_file)}`,
    'mkdir -p "$(dirname "$status_file")"',
    'printf \'last_run=%s\\n\' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" > "$status_file.tmp"',
    'rc=0',
  ];

  if (config.repository_file) {
    lines.push(
      `export RESTIC_REPOSITORY_FILE=${shellQuote(config.repository_file)}`,
    );
  } else if (config.repository) {
    lines.push(
      `export RESTIC_REPOSITORY=${shellQuote(
        renderScalar(config.repository, 'restic.repository'),
      )}`,
    );
  }
  lines.push(`export RESTIC_PASSWORD_FILE=${shellQuote(config.password_file)}`);

  const backup = [
    ...resticCommandBase(),
    'backup',
    ...(config.tag !== undefined
      ? ['--tag', renderScalar(config.tag, 'restic.tag')]
      : []),
    ...config.excludes.flatMap((exclude) => ['--exclude', exclude]),
    ...config.paths,
  ];
  lines.push(`${backup.map(shellQuote).join(' ')} || rc=$?`);

  const forget = [
    ...resticCommandBase(),
    'forget',
    ...(config.prune ? ['--prune'] : []),
    ...(config.keep_last !== undefined
      ? ['--keep-last', String(config.keep_last)]
      : []),
    ...(config.keep_daily !== undefined
      ? ['--keep-daily', String(config.keep_daily)]
      : []),
    ...(config.keep_weekly !== undefined
      ? ['--keep-weekly', String(config.keep_weekly)]
      : []),
    ...(config.keep_monthly !== undefined
      ? ['--keep-monthly', String(config.keep_monthly)]
      : []),
  ];
  if (config.prune || forget.length > 2) {
    lines.push(
      `if [ "$rc" -eq 0 ]; then ${forget.map(shellQuote).join(' ')} || rc=$?; fi`,
    );
  }

  lines.push(
    'if [ "$rc" -eq 0 ]; then',
    '  printf \'last_success=%s\\n\' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" >> "$status_file.tmp"',
    'fi',
    'mv "$status_file.tmp" "$status_file"',
    'exit "$rc"',
    '',
  );
  return lines.join('\n');
}

/** Generated `/etc/cron.d` fragment for the restic script. */
export function renderResticCron(config: ResticBackupConfig): string {
  if (!/^\S+(?:\s+\S+){4}$/.test(config.schedule)) {
    throw new HostBackupError(
      `restic.schedule '${config.schedule}' is not a five-field cron expression.`,
    );
  }
  const logPath = posix.join(
    posix.dirname(config.script_path),
    'hacm-restic.log',
  );
  return [
    '# Generated by HAC Manager (D-57). Do not edit; changes are overwritten.',
    `${config.schedule} root ${shellQuote(config.script_path)} >${shellQuote(logPath)} 2>&1`,
    '',
  ].join('\n');
}

/** Render every enabled managed file for one host. */
export function renderHostBackupFiles(
  config: HostBackupConfig,
): readonly RenderedHostBackupFile[] {
  const files: RenderedHostBackupFile[] = [];
  if (config.vzdump?.enabled !== false && config.vzdump !== undefined) {
    files.push({
      kind: 'vzdump',
      path: config.vzdump.path,
      mode: config.vzdump.mode,
      content: renderVzdumpConfig(config.vzdump),
    });
  }
  if (config.restic?.enabled !== false && config.restic !== undefined) {
    files.push({
      kind: 'restic-script',
      path: config.restic.script_path,
      mode: '0755',
      content: renderResticScript(config.restic),
    });
    files.push({
      kind: 'restic-cron',
      path: config.restic.cron_path,
      mode: '0644',
      content: renderResticCron(config.restic),
    });
  }
  return files;
}
